// A release built by the data program's release.build job: a game's from a revision of its
// project (ADR 0069 d7; project_repository.h), which the project routes' release route enqueues
// in the transaction that makes the release (building), and an app's from its uploaded build,
// which the release routes' completion enqueues once the build is in the store:
//
//   release.build  {release_id}, cap 1. The release must be building. Its project's revision
//                  is laid out from the store (every file by its SHA-256 from the program's own
//                  cache of the project's files, synced down once per build: sync_down), each in
//                  a folder of its project's key, an expansion's beside its base game's revision
//                  with the laid-out project.opennova's base_project pointed there (whatever
//                  folder its author kept the base in; one naming no base game's project is
//                  refused), and exported by opennova-project, the base first. Every package is
//                  whole (--full: every file of the export a row, so the jointops and dfx2 zips
//                  install their game into an empty folder from it), carrying the removals
//                  since the product's published release (--previous) and leaving out the
//                  runtime's own files in a game's folder (update.exe, revupdat.exe,
//                  README.txt). A retail game's also carries the removals since its stock
//                  revision (1, a fresh import of the stock install, an expansion's on its
//                  base's, exported by our own writer as the edited one is); our own game's
//                  tree gets an UPDATE.WIZ naming its product (the deployment's update host,
//                  ONNET_UPDATE_HOST, its URL), and an account's own game's names its title too
//                  (GAME=jo or dfx2, our own key, ADR 0074). Every game's gt.ssc is generated
//                  from its configured lobby, and every expansion's from its parent game's.
//                  Historical source copies are excluded. The generated bytes are passed to
//                  the exporter with --gate-tag-file and become a loose build entry (root for
//                  games, expansion/<code>/ for expansions); stock exports take the original
//                  title's tag. No release predicts a lobby from a project key or ownership.
//                  opennova-update-tool packs it with the product's
//                  command file, product name and executable. The package is put where an
//                  upload lands (release_upload_key), and the release made validating with
//                  release.validate queued, as a completed upload is, recording the ONE that
//                  built it (releases.one_version: this program's one_build()). An updatable
//                  app's (one with an updater product: the runtime, the editor) is its uploaded
//                  build
//                  (release_source_key) unpacked (core/zip_files.h, refusing a name that would
//                  leave the folder), its OPENNOVA.WIZ written from its row with this
//                  deployment's update host (refused with none), packed whole the same way
//                  against its published release, every file of its build a row (no file left
//                  out), then validated as a game's is. A download-only app's (the tools, the
//                  Blender add-on) is its build kept as uploaded under its own
//                  digest (release_download_key), the release a draft with no section. Either
//                  removes the uploaded build after. A refusal (no project, no product, a build
//                  that does not unpack, a tool failing) makes the release invalid with its
//                  reason, what the tools said kept as its build_log; a store failure runs the
//                  job again.
//
// The tools run as child processes from argv arrays (apps/common/command_runner.h), their
// environment the system's alone: they never see the store's credentials. Service policy, not a
// port.

#include "core/object_store.h"
#include "jobs/worker_pool.h"

#include <net/novaworld/db/database.h>

#include <cstdint>
#include <string>

namespace opennova::novaworld_server::hosted {

inline constexpr const char *kJobReleaseBuild = "release.build";

// What a build runs: opennova-project (its export) and opennova-update-tool (its package
// builder), by absolute path; the host our own game's UPDATE.WIZ and an updatable app's
// OPENNOVA.WIZ name (ONNET_UPDATE_HOST: "" names none in a game's, and refuses an app's build);
// how long either may run.
struct ReleaseTools {
	std::string project_tool;
	std::string update_tool;
	std::string update_host;
	int timeout_ms = 60 * 60 * 1000;
};

// The release `release_id`'s build queued; the job's id, 0 when one is queued or running.
int64_t enqueue_release_build(db::Database &db, int64_t release_id);
// That build's job's dedupe key (jobs::job_pending: whether it is queued or running).
std::string release_build_key(int64_t release_id);

// release.build's handler over `store`, its work under `scratch_dir` (the projects' files cached
// there between builds).
void register_release_build(jobs::JobRegistry &registry, ObjectStore &store,
		std::string scratch_dir, ReleaseTools tools);

} // namespace opennova::novaworld_server::hosted
