"""Writes engine/base/project/case_fold.cpp: Unicode's simple case folding as runs.

Simple case folding is CaseFolding.txt's C and S rows: one code point to one. Python's str.casefold applies the C and
F rows, so a code point whose casefold is one code point takes it (its C row), and one whose casefold is longer (an F
row) takes its lower case where that is one code point (its S row: U+1E9E and the Greek capitals with prosgegrammeni),
else stays. The runs are the mappings grouped by one delta over consecutive code points or every other one.

    python scripts/project/case_fold_table.py > engine/base/project/case_fold.cpp
"""
import sys
import unicodedata


def simple_fold(cp):
    c = chr(cp)
    folded = c.casefold()
    if len(folded) == 1:
        return ord(folded)
    lower = c.lower()
    return ord(lower) if len(lower) == 1 else cp


def runs():
    pairs = [(cp, simple_fold(cp)) for cp in range(0x110000)
             if not 0xD800 <= cp <= 0xDFFF and simple_fold(cp) != cp]
    out = []
    i = 0
    while i < len(pairs):
        first, to = pairs[i]
        delta = to - first
        best_n, best_stride = 1, 1
        for stride in (1, 2):
            n = 1
            while (i + n < len(pairs) and pairs[i + n][0] == first + n * stride
                   and pairs[i + n][1] - pairs[i + n][0] == delta):
                n += 1
            if n > best_n:
                best_n, best_stride = n, stride
        out.append((first, first + (best_n - 1) * best_stride, delta, best_stride))
        i += best_n
    return out


def main():
    sys.stdout.reconfigure(newline="\n")
    table = runs()
    w = sys.stdout.write
    w("// Generated by scripts/project/case_fold_table.py from Unicode %s's simple case folding (CaseFolding.txt's C\n"
      % unicodedata.unidata_version)
    w("// and S rows); do not edit by hand.\n")
    w("#include <base/project/case_fold.h>\n\n#include <cstddef>\n\nnamespace opennova::project {\n\nnamespace {\n\n")
    w("// The code points first..last, every `stride`th, each folding to itself plus `delta`.\n")
    w("struct FoldRun {\n\tuint32_t first;\n\tuint32_t last;\n\tint32_t delta;\n\tuint32_t stride;\n};\n\n")
    w("constexpr FoldRun kFoldRuns[] = {\n")
    for first, last, delta, stride in table:
        w("\t{ 0x%05X, 0x%05X, %d, %d },\n" % (first, last, delta, stride))
    w("};\n\n} // namespace\n\n")
    w("uint32_t simple_case_fold(uint32_t code_point) {\n")
    w("\tsize_t lo = 0, hi = sizeof(kFoldRuns) / sizeof(kFoldRuns[0]);\n")
    w("\twhile (lo < hi) {\n\t\tconst size_t mid = lo + (hi - lo) / 2;\n")
    w("\t\tif (kFoldRuns[mid].first <= code_point) lo = mid + 1;\n\t\telse hi = mid;\n\t}\n")
    w("\tif (lo == 0) return code_point;\n\tconst FoldRun &run = kFoldRuns[lo - 1];\n")
    w("\tif (code_point > run.last || (code_point - run.first) % run.stride != 0) return code_point;\n")
    w("\treturn static_cast<uint32_t>(static_cast<int64_t>(code_point) + run.delta);\n}\n\n")
    w("} // namespace opennova::project\n")


if __name__ == "__main__":
    main()
