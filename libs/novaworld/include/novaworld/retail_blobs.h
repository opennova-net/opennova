#pragma once

// Byte-exact payloads extracted from the user's retail JO install
// (JO_CLIENT/localres.pff → ASH_I5A.bms, 2026-04-23). The 616-byte
// header of ASH_I5A.bms IS the tag=0x0B mission blob the client
// expects; copying the real file header means byte_A761D0 gets exactly
// what the client would load if it opened the file locally.
//
// Why dvxi5 (Dormant Volcano Isle) instead of capture2's g11 (Kendari):
// dvxi5.trn + dvxi5_c.tga + dvxi5.cpt + dvxi5_f/m.pcx all live in
// resource.pff, which the client loads unconditionally at startup. The
// g11 assets are in expansion/jox01/jox01.pff — that expansion PFF may
// not be in the search path when joining a remote server, so the first
// attempt at Kendari failed with "Mission loading aborted" (sub_520710
// → sub_610940 → sub_57DB30 couldn't open g11.trn).
//
// Decoded offsets in this blob:
//   [0..3]    : "BMS\x13" signature
//   [4..35]   : mission display name ("AS - Dormant Volcano Isle")
//   [36..67]  : author ("Brophy / Brent / BB")
//   [68..99]  : map ID ("dvxi5") → MultiByteStr in sub_610940
//   [120..135]: "Default" + padding
//   [136..139]: game type u32 = 0x00010003 (TDM? observed 0x00010002
//               in capture2 for g11; 0x00010003 here for dvxi5)
//   [140..175]: mpattrib + timestamps + numeric fields
//   [216..247]: unused in this BMS (empty)
//   [244..247]: "full_00" icon key — overwrites earlier zeros
//   [276..307]: terrain atlas key ("trntile10")
//   [308..615]: remaining header metadata + padding

