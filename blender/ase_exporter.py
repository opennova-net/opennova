    def _prepare_triangulated_mesh(self, obj):
        """Prepare a triangulated temp mesh.

        Returns (mesh_eval, bm, temp_mesh, neg_scale, orig_edge_keys).
        """
        mesh = obj.data

        depsgraph = bpy.context.evaluated_depsgraph_get()
        obj_eval = obj.evaluated_get(depsgraph)
        mesh_eval = obj_eval.data

        bm = None
        if all(len(poly.vertices) == 3 for poly in mesh_eval.polygons):
            # Preserve original polygon/loop ordering when the mesh is already
            # triangulated. Re-triangulating with bmesh can reshuffle triangles
            # and shift face-normal insertion order in OED collision export.
            temp_mesh = mesh_eval.copy()
        else:
            bm = bmesh.new()
            bm.from_mesh(mesh_eval)
            bmesh.ops.triangulate(bm, faces=bm.faces)
            temp_mesh = bpy.data.meshes.new("temp_export")
            bm.to_mesh(temp_mesh)
        temp_mesh.calc_loop_triangles()
        self._ensure_split_normals(temp_mesh)

        neg_scale = obj.matrix_world.determinant() < 0
        orig_edge_keys = {tuple(sorted(edge.vertices)) for edge in mesh_eval.edges}

        return mesh_eval, bm, temp_mesh, neg_scale, orig_edge_keys

    def _ensure_split_normals(self, mesh):
        """Ensure split normals are available across Blender versions."""
        if hasattr(mesh, "calc_normals_split"):
            mesh.calc_normals_split()
            return True
        if hasattr(mesh, "calc_normals"):
            mesh.calc_normals()
        return False

