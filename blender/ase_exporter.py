    def _fix_tex_ext(self, name):
        """Fix texture extensions for df4oed compatibility.

        df4oed only supports TGA/PCX/MDT in ASE files.
        DDS textures are auto-loaded as fallback, so we map .dds -> .tga
        """
        if not name:
            return name
        name = os.path.basename(name)
        root, ext = os.path.splitext(name)
        if ext.upper() in ('.TGA', '.PCX', '.MDT'):
            return root + ext
        return root + '.tga'

    def _fit_texture_name(self, name):
        """Shorten a texture filename to fit OED's 15-char limit.

        Truncates the stem, preserving the extension.  Appends a digit
        suffix when truncation would create a duplicate.

        Returns the (possibly shortened) filename.
        """
        if not name:
            return name
        if len(name) <= self.MAX_TEX_FILENAME:
            self._used_tex_names[name.lower()] = name.lower()
            return name

        root, ext = os.path.splitext(name)
        max_stem = self.MAX_TEX_FILENAME - len(ext)

        candidate = root[:max_stem] + ext
        key = candidate.lower()

        # Deduplicate: if this short name is already taken by a DIFFERENT
        # original name, shorten further and append a digit.
        if key in self._used_tex_names and self._used_tex_names[key] != name.lower():
            for i in range(2, 100):
                suffix = str(i)
                candidate = root[:max_stem - len(suffix)] + suffix + ext
                key = candidate.lower()
                if key not in self._used_tex_names:
                    break

        self._used_tex_names[key] = name.lower()
        if candidate != name:
            print(f"ASE Export: Texture name shortened: '{name}' -> '{candidate}'")
        return candidate

    def _find_bitmap_from_nodes(self, material):
        """Extract a bitmap path and Image object from the Blender shader node tree.

        Returns (path_string, bpy.types.Image or None).
        """
        def find_image_from_socket(socket, visited=None):
            if not socket or not socket.is_linked:
                return None
            return find_image_from_node(socket.links[0].from_node, visited)

        def find_image_from_node(node, visited=None):
            if visited is None:
                visited = set()
            if id(node) in visited:
                return None
            visited.add(id(node))
            if node.type == 'TEX_IMAGE' and node.image:
                return node.image
            if node.type == 'NORMAL_MAP':
                return find_image_from_socket(node.inputs.get('Color'), visited)
            for inp in node.inputs:
                if inp.is_linked:
                    img = find_image_from_socket(inp, visited)
                    if img:
                        return img
            return None

        principled = None
        for node in material.node_tree.nodes:
            if node.type == 'BSDF_PRINCIPLED':
                principled = node
                break

        image = None
        if principled:
            image = find_image_from_socket(principled.inputs.get('Base Color'))
        if image is None:
            for node in material.node_tree.nodes:
                if node.type == 'TEX_IMAGE' and node.image:
                    image = node.image
                    break

        if image:
            path = image.filepath or image.filepath_raw or image.name or ""
            if path:
                path = bpy.path.abspath(path)
            return path, image
        return "", None

    @staticmethod
    def _clean_blender_duplicate_suffix(name: str) -> str:
        if len(name) > 4 and name[-4] == "." and name[-3:].isdigit():
            return name[:-4]
        return name

    def _shader_from_material_name(self, material):
        if not material:
            return ""
        name = self._clean_blender_duplicate_suffix(material.name)
        if not name.startswith("Material_"):
            return ""
        rest = name[len("Material_"):]
        parts = rest.split("_", 1)
        if len(parts) != 2:
            return ""
        try:
            int(parts[0])
        except ValueError:
            return ""
        return parts[1] or ""

    def _material_export_name(self, material, index: int, shader_code: str) -> str:
        if material:
            name = self._clean_blender_duplicate_suffix(material.name)
            if name.startswith("Material_"):
                return name
        return f"Material_{index}_{shader_code}"

    def _derive_opennova_shader(self, material, is_skinned):
        """Derive OED shader code from Blender material's node tree.

        Inspects the Principled BSDF node for bump, specular, emission,
        alpha, glass, and detail texture presence to select the appropriate
        OED shader. Returns the shader code string (e.g. 'VS_PHONGT').
        """
        if not material or not material.use_nodes or not material.node_tree:
            return "VS_SKBASIC" if is_skinned else "FF_ST_OP"

        nodes = material.node_tree.nodes
        links = material.node_tree.links

        # Find Principled BSDF
        bsdf = None
        for node in nodes:
            if node.type == 'BSDF_PRINCIPLED':
                bsdf = node
                break
        if not bsdf:
            return "VS_SKBASIC" if is_skinned else "FF_ST_OP"

        # Detect features from node tree
        has_bump = False
        normal_input = bsdf.inputs.get("Normal")
        if normal_input and normal_input.is_linked:
            from_node = normal_input.links[0].from_node
            if from_node.type == 'BUMP':
                has_bump = True

        has_specular = False
        spec_input = bsdf.inputs.get("Specular IOR Level") or bsdf.inputs.get("Specular")
        if spec_input and not spec_input.is_linked:
            has_specular = spec_input.default_value > 0

        is_emissive = False
        emission_input = bsdf.inputs.get("Emission Strength")
        if emission_input and not emission_input.is_linked:
            is_emissive = emission_input.default_value > 0

        is_alpha = False
        if hasattr(material, 'blend_method'):
            is_alpha = material.blend_method not in ("OPAQUE", "CLIP")
        alpha_input = bsdf.inputs.get("Alpha")
        if alpha_input and alpha_input.is_linked:
            is_alpha = True

        is_glass = False
        trans_input = (bsdf.inputs.get("Transmission Weight")
                       or bsdf.inputs.get("Transmission"))
        if trans_input and not trans_input.is_linked:
            is_glass = trans_input.default_value > 0

        # Count connected texture images
        tex_count = 0
        for node in nodes:
            if node.type == 'TEX_IMAGE' and node.image:
                # Only count textures that feed into the material
                for output in node.outputs:
                    if output.is_linked:
                        tex_count += 1
                        break

        # Detect detail texture (MixRGB Multiply feeding Base Color)
        has_detail = self._has_mix_multiply_detail(material)

        # Shader selection logic
        if is_glass:
            return "VS_SKGLASS" if is_skinned else "FFP_GLASS"

        if has_bump:
            if has_specular:
                return "VS_SKBUMPPHONGT" if is_skinned else "VS_PHONGT"
            else:
                return "VS_SKBUMPDIFFT" if is_skinned else "VS_DOT3DIFF"

        if has_detail or tex_count >= 2:
            if is_emissive:
                return "FF_MT_OP_LUM"
            elif is_alpha:
                return "FF_MT_AB"
            else:
                return "FF_MT_OP"

        # Single texture (or no texture)
        if is_skinned:
            return "VS_SKBASIC"

        if is_emissive:
            return "FF_ST_OP_LUM"
        elif is_alpha:
            return "FF_ST_AB"
        else:
            return "FF_ST_OP"

    def _has_mix_multiply_detail(self, material):
        """Check if material has a MixRGB/Mix Multiply node feeding Base Color."""
        if not material.use_nodes or not material.node_tree:
            return False

        bsdf = None
        for node in material.node_tree.nodes:
            if node.type == 'BSDF_PRINCIPLED':
                bsdf = node
                break
        if not bsdf:
            return self._find_named_detail_image(material) is not None

        base_color = bsdf.inputs.get("Base Color")
        if not base_color or not base_color.is_linked:
            return self._find_named_detail_image(material) is not None

        from_node = base_color.links[0].from_node
        # ShaderNodeMixRGB (Blender 3.x) or ShaderNodeMix (Blender 4.x)
        if from_node.type == 'MIX_RGB' and from_node.blend_type == 'MULTIPLY':
            return True
        if from_node.type == 'MIX' and hasattr(from_node, 'data_type'):
            if from_node.data_type == 'RGBA' and from_node.blend_type == 'MULTIPLY':
                return True
        return self._find_named_detail_image(material) is not None

    @staticmethod
    def _find_named_detail_image(material):
        for node in material.node_tree.nodes:
            if node.type != 'TEX_IMAGE' or not node.image:
                continue
            label = getattr(node, "label", "") or ""
            marker = f"{node.name} {label}".lower()
            if "detail" in marker:
                return node.image
        return None

    @staticmethod
    def _image_path(image):
        path = image.filepath or image.filepath_raw or image.name or ""
        if path:
            path = bpy.path.abspath(path)
        return path

    def _find_detail_from_nodes(self, material):
        """Extract detail/lightmap texture from Blender material nodes.

        Returns (path_string, bpy.types.Image or None).
        """
        if not material.use_nodes or not material.node_tree:
            return "", None

        bsdf = None
        for node in material.node_tree.nodes:
            if node.type == 'BSDF_PRINCIPLED':
                bsdf = node
                break
        if not bsdf:
            return "", None

        base_color = bsdf.inputs.get("Base Color")
        if not base_color or not base_color.is_linked:
            image = self._find_named_detail_image(material)
            if image:
                return self._image_path(image), image
            return "", None

        mix_node = base_color.links[0].from_node
        is_multiply = False
        if mix_node.type == 'MIX_RGB' and mix_node.blend_type == 'MULTIPLY':
            is_multiply = True
        elif (mix_node.type == 'MIX' and hasattr(mix_node, 'data_type')
              and mix_node.data_type == 'RGBA'
              and mix_node.blend_type == 'MULTIPLY'):
            is_multiply = True

        if not is_multiply:
            image = self._find_named_detail_image(material)
            if image:
                return self._image_path(image), image
            return "", None

        # The second input of MixRGB is the detail/lightmap texture.
        # For MIX_RGB: inputs[1]=Color1 (diffuse), inputs[2]=Color2 (detail)
        # For MIX (4.x): inputs["B"] is the second color
        detail_input = None
        if mix_node.type == 'MIX_RGB':
            detail_input = mix_node.inputs[2] if len(mix_node.inputs) > 2 else None
        elif mix_node.type == 'MIX':
            detail_input = mix_node.inputs.get("B")

        if not detail_input or not detail_input.is_linked:
            image = self._find_named_detail_image(material)
            if image:
                return self._image_path(image), image
            return "", None

        tex_node = detail_input.links[0].from_node
        if tex_node.type == 'TEX_IMAGE' and tex_node.image:
            image = tex_node.image
            return self._image_path(image), image

        image = self._find_named_detail_image(material)
        if image:
            return self._image_path(image), image
        return "", None

    def _get_material_diffuse(self, material):
        """Extract diffuse color from a Blender material. Returns (r, g, b)."""
        if material.use_nodes and material.node_tree:
            for node in material.node_tree.nodes:
                if node.type == 'BSDF_PRINCIPLED':
                    inp = node.inputs.get('Base Color')
                    if inp and not inp.is_linked:
                        return (inp.default_value[0], inp.default_value[1],
                                inp.default_value[2])
                    break
        return (material.diffuse_color[0], material.diffuse_color[1],
                material.diffuse_color[2])

    def _get_material_specular(self, material):
        """Extract specular color from a Blender material. Returns (r, g, b)."""
        if material.use_nodes and material.node_tree:
            for node in material.node_tree.nodes:
                if node.type == 'BSDF_PRINCIPLED':
                    inp = node.inputs.get('Specular IOR Level')
                    if inp and not inp.is_linked:
                        s = inp.default_value
                        return (s, s, s)
                    break
        return (0.9, 0.9, 0.9)

    def _get_material_shine(self, material):
        """Extract shine (glossiness) from a Blender material. Returns float 0..1."""
        if material.use_nodes and material.node_tree:
            for node in material.node_tree.nodes:
                if node.type == 'BSDF_PRINCIPLED':
                    inp = node.inputs.get('Roughness')
                    if inp and not inp.is_linked:
                        return 1.0 - inp.default_value  # invert roughness
                    break
        return 0.1

    def _get_material_transparency(self, material):
        """Extract transparency from a Blender material. Returns float 0..1."""
        if material.use_nodes and material.node_tree:
            for node in material.node_tree.nodes:
                if node.type == 'BSDF_PRINCIPLED':
                    inp = node.inputs.get('Alpha')
                    if inp and not inp.is_linked:
                        return 1.0 - inp.default_value  # alpha to transparency
                    break
        return 0.0

    def _save_textures(self, output_dir):
        """Save queued texture images as TGA files alongside the ASE."""
        for filename, image in self._texture_queue.items():
            dest = os.path.join(output_dir, filename)
            if os.path.exists(dest):
                print(f"ASE Export: Texture already exists, skipping: {filename}")
                continue

            try:
                # Save via a temporary settings override to force TGA output.
                orig_path = image.filepath_raw
                orig_format = image.file_format

                image.filepath_raw = dest
                image.file_format = 'TARGA_RAW'  # uncompressed — avoids RLE+top-origin issues in stb_image
                image.save()

                # Restore original values
                image.filepath_raw = orig_path
                image.file_format = orig_format

                print(f"ASE Export: Saved texture {filename}")
            except Exception as e:
                print(f"ASE Export: Failed to save texture {filename}: {e}")
