        # Faces
        for i, (a, b, c) in enumerate(face_indices):
            face = ase_obj.faces[i]
            face.vert[0], face.vert[1], face.vert[2] = a, b, c
            face.smoothing_mask = 0
            face.material_id = 0
            face.edge_visibility[0] = 1
            face.edge_visibility[1] = 1
            face.edge_visibility[2] = 1

